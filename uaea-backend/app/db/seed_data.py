def course_plan(code: str) -> list[list[tuple[str, int]]]:
    """Return [[(title, credit_hours), …] per semester] for a programme."""
    prog = PROGRAM_BY_CODE[code]
    n_sem = prog["semesters"]
    if code in COURSE_POOLS:
        return [[(t, 3 if "Project" not in t else 3) for t in sem] for sem in COURSE_POOLS[code]]
    pool = GENERIC_SUBJECTS[code]
    if prog["level"] == "Undergraduate":
        per_sem = 5
    elif code in ("MSCS", "MPHILEDU", "PHDCS"):
        per_sem = 3 if code != "PHDCS" else 2
    else:
        per_sem = 4 if code != "BED15" else 5
    plan: list[list[tuple[str, int]]] = []
    idx = 0
    for s in range(n_sem):
        sem: list[tuple[str, int]] = []
        for _ in range(per_sem):
            # undergrad programmes mix in general-education courses early on
            if prog["level"] == "Undergraduate" and s < 4 and len(sem) == per_sem - 1:
                sem.append((GEN_ED[s % len(GEN_ED)], 2))
            else:
                sem.append((pool[idx % len(pool)], 3))
                idx += 1
        plan.append(sem)
    return plan


